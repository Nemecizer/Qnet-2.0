// Measures how long one run of each method took in the recorded corpus and writes the table the
// What-If Sweep panel estimates from (src/sweeps/pointSeconds.ts). Run from the repository root
// after the corpus is re-recorded:
//
//   node src/sweeps/measure-point-seconds.mjs
//
// The rule (src/sweeps/sweeps.test.tsx recomputes it and fails when the table and the corpus
// differ): per run label, the median `elapsedSeconds` of every golden/runs/<example>/<label>/
// record.json whose status is "completed" or "partial", rounded to a hundredth of a second, with
// the number of runs it is the median of. A label with no such record has no row.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const runs = join(here, "../../golden/runs");
const byLabel = new Map();
for (const example of readdirSync(runs).sort()) {
  let labels = [];
  try {
    labels = readdirSync(join(runs, example));
  } catch {
    continue;
  }
  for (const label of labels) {
    const file = join(runs, example, label, "record.json");
    if (!existsSync(file)) continue;
    const record = JSON.parse(readFileSync(file, "utf8"));
    if ((record.status !== "completed" && record.status !== "partial") || !Number.isFinite(record.elapsedSeconds)) continue;
    if (!byLabel.has(label)) byLabel.set(label, []);
    byLabel.get(label).push(record.elapsedSeconds);
  }
}
const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const mid = s.length >> 1;
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};
const rows = [...byLabel.keys()].sort().map((label) => `  ${/^[a-z_]+$/.test(label) ? label : JSON.stringify(label)}: { seconds: ${Number(median(byLabel.get(label)).toFixed(2))}, runs: ${byLabel.get(label).length} },`);
const text = `// GENERATED by src/sweeps/measure-point-seconds.mjs from golden/runs — do not edit by hand.
// Per run label: the median seconds one recorded run took (completed or partial runs of the
// example networks, at the corpus's settings), and how many runs that is the median of.
export const MEASURED_SECONDS: Record<string, { seconds: number; runs: number }> = {
${rows.join("\n")}
};
`;
writeFileSync(join(here, "pointSeconds.ts"), text);
